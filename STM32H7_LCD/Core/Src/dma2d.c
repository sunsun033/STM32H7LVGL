#include "lcd_format.h"

/* USER CODE END 0 */

DMA2D_HandleTypeDef hdma2d;

/* DMA2D init function */
void MX_DMA2D_Init(void)
{

  /* USER CODE BEGIN DMA2D_Init 0 */

  /* USER CODE END DMA2D_Init 0 */

  /* USER CODE BEGIN DMA2D_Init 1 */

  /* USER CODE END DMA2D_Init 1 */
  hdma2d.Instance = DMA2D;
  hdma2d.Init.Mode = DMA2D_M2M;
  hdma2d.Init.ColorMode = DMA2D_OUTPUT_ARGB8888;
  hdma2d.Init.OutputOffset = 0;
  hdma2d.LayerCfg[1].InputOffset = 0;
  hdma2d.LayerCfg[1].InputColorMode = DMA2D_INPUT_ARGB8888;
  hdma2d.LayerCfg[1].AlphaMode = DMA2D_NO_MODIF_ALPHA;
  hdma2d.LayerCfg[1].InputAlpha = 0;
  hdma2d.LayerCfg[1].AlphaInverted = DMA2D_REGULAR_ALPHA;
  hdma2d.LayerCfg[1].RedBlueSwap = DMA2D_RB_REGULAR;
  hdma2d.LayerCfg[1].ChromaSubSampling = DMA2D_NO_CSS;
  if (HAL_DMA2D_Init(&hdma2d) != HAL_OK)
  {
    Error_Handler();
  }
  if (HAL_DMA2D_ConfigLayer(&hdma2d, 1) != HAL_OK)
  {
    Error_Handler();
  }
  /* USER CODE BEGIN DMA2D_Init 2 */

  /* ★★ 同理：DMA2D 的输出/输入格式也由代码说了算 ★★
     上面两行是 CubeMX 生成的，这里按 lcd_format.h 覆盖并重新初始化。
     放在 USER CODE 区，重新生成代码不会丢。

     （其实 Hardware/lcd.c 的 lcd_fill() 每次清屏前都会自己 Init 一次，
       这里主要是为了 M2M 等其它用法时句柄里的配置也是对的。） */
  if (hdma2d.Init.ColorMode != LCD_DMA2D_OUTPUT_MODE)
  {
    hdma2d.Init.ColorMode             = LCD_DMA2D_OUTPUT_MODE;
    hdma2d.LayerCfg[1].InputColorMode = LCD_DMA2D_INPUT_MODE;

    if (HAL_DMA2D_Init(&hdma2d) != HAL_OK)
    {
      Error_Handler();
    }
    if (HAL_DMA2D_ConfigLayer(&hdma2d, 1) != HAL_OK)
    {
      Error_Handler();
    }
  }

  /* USER CODE END DMA2D_Init 2 */

}


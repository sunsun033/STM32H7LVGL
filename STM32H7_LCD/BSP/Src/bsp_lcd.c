/* ======================== DMA2D config ======================== */

/* The LTDC layer is ARGB8888, so DMA2D must output ARGB8888 as well.
   Note the naming mismatch between the two peripherals:
       LTDC_PIXEL_FORMAT_ARGB8888  <->  DMA2D_OUTPUT_ARGB8888   (correct pair)
       LTDC_PIXEL_FORMAT_RGB888    <->  DMA2D_OUTPUT_ARGB8888   (NOT DMA2D_OUTPUT_RGB888)
   DMA2D's "RGB888" packs the channels differently, so pairing it with an
   LTDC ARGB8888 layer swaps colour channels.
   Fill operations use Register-to-Memory (R2M) mode.
   CubeMX generates MX_DMA2D_Init() as M2M + ARGB8888, which happens to match,
   but we reconfigure here to be explicit and to force R2M. */
static void lcd_dma2d_config_r2m(void)
{
    hdma2d.Init.Mode         = DMA2D_R2M;
    hdma2d.Init.ColorMode    = DMA2D_OUTPUT_ARGB8888;
    hdma2d.Init.OutputOffset = 0U;
    (void)HAL_DMA2D_Init(&hdma2d);
}

/* ======================== Public API ======================== */

void bsp_lcd_backlight(uint8_t on)
{
    HAL_GPIO_WritePin(LCD_BL_EN_GPIO_Port, LCD_BL_EN_Pin,
                      (on != 0U) ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

/* Prepare the display: DMA2D config + clear to black.
   The backlight is deliberately NOT turned on here.

   Reason: the touch controller's reset pin (PG14 / LCD_TP_RST) is SHARED with
   the panel's reset pin (FPC pin 31 P_RESET).  Initialising the GT911 therefore
   also resets the panel, which blanks the picture for ~20 ms.  If the backlight
   is already on, the user sees the screen flash and redraw.

   Correct start-up order:
       bsp_lcd_init();            <- display ready, backlight still OFF
       ...draw whatever you like...   (invisible so far)
       bsp_gt911_init();          <- panel+touch reset happens here, unseen
       bsp_lcd_backlight(1U);     <- now show everything, no flicker */
void bsp_lcd_init(void)
{
    lcd_dma2d_config_r2m();
    bsp_lcd_clear(LCD_COLOR_BLACK);
}

